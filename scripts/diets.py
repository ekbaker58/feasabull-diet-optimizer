"""Diets: read config/diets.json, check it, and turn it into what the optimizer uses.

    python scripts/diets.py            check config/diets.json and list what each diet excludes

A diet in config/diets.json:
    { "name": "Nut-Free", "description": "...",
      "protein_pct": [10, 35], "carbs_pct": [45, 65], "fat_pct": [20, 35],
      "no": ["Nuts & Seeds", "peanut_butter"] }

Each entry in "no" can be any of (not case-sensitive):
    a food attribute   red meat (includes pork), pork, poultry, fish, eggs, dairy, gluten
    a food group       e.g. "Snacks & Sweets"
    a food type        e.g. "Nuts & Seeds", "Grains & Bread"
    one food           its id or name, e.g. "peanut_butter" or "Peanut butter"
The full list of valid names is docs/FOOD_LIST.md (regenerated by scripts/build_data.py).

In the model, a diet changes two things: the macro rows of b (protein/carb/fat share of calories) and the upper
bounds u (an excluded food gets u = 0). Attributes stay a separate list ("forbid") because the spreadsheet tests
them with a dot product; everything else is expanded here into a list of food ids ("forbid_foods").
"""
import difflib, json, os, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
DIETS_FILE = os.path.join(ROOT, 'config', 'diets.json')

# attribute key -> words people might write for it
ATTR_ALIASES = {
    # exact synonyms only: "beef" would also catch pork (pork foods carry the meat flag), "wheat" would catch oats
    'meat': ['meat', 'red meat'], 'pork': ['pork'], 'poultry': ['poultry'],
    'fish': ['fish', 'seafood', 'fish & seafood'], 'egg': ['egg', 'eggs'], 'dairy': ['dairy'],
    'gluten': ['gluten'],
}
MACROS = [('protein_pct', 'protein'), ('carbs_pct', 'carb'), ('fat_pct', 'fat')]
FIELDS = {'name', 'description', 'protein_pct', 'carbs_pct', 'fat_pct', 'no'}


class DietError(Exception):
    pass


def _norm(s):
    return ' '.join(str(s).lower().replace('_', ' ').split())


def _vocabulary(foods):
    """Every name an entry in "no" may use -> ('attr', key) or ('foods', [ids])."""
    vocab = {}
    for key, words in ATTR_ALIASES.items():
        for w in words:
            vocab[_norm(w)] = ('attr', key)
    for field in ('group', 'type'):
        for value in dict.fromkeys(f[field] for f in foods):
            vocab.setdefault(_norm(value), ('foods', [f['id'] for f in foods if f[field] == value]))
    for f in foods:
        vocab.setdefault(_norm(f['id']), ('foods', [f['id']]))
        vocab.setdefault(_norm(f['name']), ('foods', [f['id']]))
    return vocab


def _check_range(diet_name, field, value, errors):
    if not (isinstance(value, list) and len(value) == 2 and all(isinstance(v, (int, float)) and not isinstance(v, bool) for v in value)):
        errors.append(f'{diet_name}: "{field}" must be two numbers [min, max] in percent, e.g. [10, 35]; got {json.dumps(value)}')
        return None
    lo, hi = value
    if not (0 <= lo <= hi <= 100):
        errors.append(f'{diet_name}: "{field}" must satisfy 0 <= min <= max <= 100 (percent of calories); got [{lo}, {hi}]')
        return None
    return lo / 100, hi / 100


def load_diets(foods, path=DIETS_FILE):
    """Return the diets in the internal format, or raise DietError listing every problem found."""
    try:
        with open(path, encoding='utf-8') as fh:
            raw = json.load(fh)
    except json.JSONDecodeError as e:
        raise DietError(f'{os.path.relpath(path, ROOT)} is not valid JSON: {e.msg} at line {e.lineno}, column {e.colno}. '
                        'Common causes: a missing comma between entries, a trailing comma before ] or }, or curly quotes.')
    items = raw.get('diets') if isinstance(raw, dict) else None
    if not isinstance(items, list) or not items:
        raise DietError('config/diets.json must contain "diets": [ ... ] with at least one diet')

    vocab = _vocabulary(foods)
    order = {f['id']: i for i, f in enumerate(foods)}
    errors, out, seen = [], [], set()
    for k, d in enumerate(items):
        label = d.get('name') if isinstance(d, dict) and d.get('name') else f'diet #{k + 1}'
        if not isinstance(d, dict):
            errors.append(f'{label}: each diet must be an object {{ ... }}'); continue
        for extra in sorted(set(d) - FIELDS):
            hint = difflib.get_close_matches(extra, FIELDS, n=1)
            errors.append(f'{label}: unknown field "{extra}"' + (f' (did you mean "{hint[0]}"?)' if hint else ''))
        name, desc = d.get('name'), d.get('description')
        if not isinstance(name, str) or not name.strip():
            errors.append(f'{label}: "name" is required'); continue
        if name.strip().lower() in seen:
            errors.append(f'{label}: another diet already uses this name')
        seen.add(name.strip().lower())
        if not isinstance(desc, str) or not desc.strip():
            errors.append(f'{label}: "description" is required (one line shown under the diet menu)')
        ranges = {}
        for field, key in MACROS:
            if field not in d:
                errors.append(f'{label}: "{field}" is required, e.g. "{field}": [10, 35]'); continue
            r = _check_range(label, field, d[field], errors)
            if r: ranges[key] = r
        if len(ranges) == 3:
            lo = sum(r[0] for r in ranges.values()); hi = sum(r[1] for r in ranges.values())
            if lo > 1 + 1e-9:
                errors.append(f'{label}: the three minimums add up to {lo * 100:g}%, more than 100% of calories, so no plan can exist')
            if hi < 1 - 1e-9:
                errors.append(f'{label}: the three maximums add up to {hi * 100:g}%, less than 100% of calories, so no plan can exist')
        no = d.get('no', [])
        if not isinstance(no, list) or not all(isinstance(x, str) for x in no):
            errors.append(f'{label}: "no" must be a list of names in quotes, e.g. ["pork", "Nuts & Seeds"]'); no = []
        attrs, ids = [], set()
        for entry in no:
            hit = vocab.get(_norm(entry))
            if hit is None:
                hint = difflib.get_close_matches(_norm(entry), list(vocab), n=3, cutoff=0.6)
                errors.append(f'{label}: "{entry}" in "no" is not an attribute, food group, food type or food'
                              + (f' (closest: {", ".join(hint)})' if hint else '') + '. See docs/FOOD_LIST.md')
            elif hit[0] == 'attr':
                attrs.append(hit[1])
            else:
                ids.update(hit[1])
        if errors and any(e.startswith(label + ':') for e in errors):
            continue
        flagged = {f['id'] for f in foods if any(a in f['flags'] for a in attrs)}
        allowed = [f for f in foods if f['id'] not in ids and f['id'] not in flagged]
        if not allowed:
            errors.append(f'{label}: "no" excludes every food'); continue
        out.append(dict(name=name.strip(), desc=desc.strip(), protein=ranges['protein'], carb=ranges['carb'], fat=ranges['fat'],
                        forbid=sorted(dict.fromkeys(attrs), key=list(ATTR_ALIASES).index),
                        forbid_foods=sorted(ids, key=order.get), no=list(no)))
    if errors:
        raise DietError('Problems in config/diets.json:\n  - ' + '\n  - '.join(errors))
    return out


def main():
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    try:
        from foods_v2 import FOODS, DIETS
    except DietError as e:
        print(e); sys.exit(1)
    print(f'config/diets.json is valid: {len(DIETS)} diets\n')
    for d in DIETS:
        out = [f['name'] for f in FOODS if f['id'] in d['forbid_foods'] or any(a in f['flags'] for a in d['forbid'])]
        pct = lambda r: f'{r[0] * 100:g}-{r[1] * 100:g}%'
        print(f"{d['name']}: protein {pct(d['protein'])}, carbs {pct(d['carb'])}, fat {pct(d['fat'])}; "
              f"{len(FOODS) - len(out)} of {len(FOODS)} foods allowed")
        if out: print('   excludes: ' + ', '.join(out))
    print('\nNext: python scripts/build_all.py  (or just commit; GitHub Actions rebuilds and checks every diet)')


if __name__ == '__main__':
    main()
