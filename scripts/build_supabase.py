"""Generate the Supabase data migration from data/foods.json (upserts, safe to re-run).
Output: supabase/migrations/20261026193100_seed_diet_data.sql  (the first load of the data)

    python scripts/build_supabase.py --release
also writes a NEW migration supabase/migrations/<UTC timestamp>_update_diet_data.sql with the same upserts.
Supabase applies each migration file once and never re-runs one it has already applied, so after the database
exists, changed prices/foods/diets only reach it through a new migration file. Make one when you want the
database updated, commit it, and merge (see docs/SUPABASE.md).
"""
import datetime, json, os, sys
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
D = json.load(open(os.path.join(ROOT, 'data', 'foods.json')))

def q(v):
    if v is None: return 'null'
    if isinstance(v, bool): return 'true' if v else 'false'
    if isinstance(v, (int, float)): return repr(round(v, 6)) if isinstance(v, float) else str(v)
    if isinstance(v, (list, tuple)): return "array[" + ",".join(q(x) for x in v) + "]::text[]" if v else "'{}'::text[]"
    return "'" + str(v).replace("'", "''") + "'"

def observed(note):
    if 'Jun 2025' in note: return '2025-06-27'
    if 'Jul 2025' in note: return '2025-07-29'
    if 'BLS Sep 2026' in note: return '2026-09-30'
    if 'undated' in note: return None
    return '2026-10-26'

out = ["-- GENERATED by scripts/build_supabase.py from data/foods.json — edit scripts/foods_v2.py, not this file.",
       "-- Upserts: re-running updates prices/nutrients in place.", ""]
fcols = ['id', 'name', 'buy_name', 'food_group', 'food_type', 'sort_order', 'store_product', 'price', 'package_g', 'edible_yield',
         'cook_yield', 'waste', 'price_note',
         'price_observed', 'bls_price', 'bls_unit_g', 'serving_g', 'serving_desc', 'max_servings', 'meal_breakfast', 'meal_lunch',
         'meal_dinner', 'meal_snacks', 'flags', 'cup_eq_g', 'cap_group', 'dga_group', 'dga_serving_g', 'refined_serving_g',
         'variety_key', 'satfat', 'usda_ndb', 'usda_desc',
         'kcal', 'protein', 'carb', 'fat', 'fiber', 'sugar', 'calcium', 'iron', 'potassium', 'sodium', 'vitc']
rows = []
NUT = ['kcal', 'protein', 'carb', 'fat', 'fiber', 'sugar', 'calcium', 'iron', 'potassium', 'sodium', 'vitc']
for i, f in enumerate(D['foods']):
    p = f['per100g']; bls = f['bls'] or [None, None]; obs = observed(f['price_note'])
    row = dict(id=f['id'], name=f['name'], buy_name=f['buy_name'], food_group=f['group'], food_type=f['type'], sort_order=i + 1,
               store_product=f['product'], price=f['price'], package_g=f['package_g'], edible_yield=f['edible_yield'],
               cook_yield=f['cook_yield'], waste=f['waste'], price_note=f['price_note'] or None,
               price_observed=None if obs is None else f"'{obs}'::date", bls_price=bls[0],
               bls_unit_g=None if bls[1] is None else round(bls[1], 4), serving_g=f['serving_g'], serving_desc=f['serving_desc'],
               max_servings=f['max_servings'], meal_breakfast=f['meal'][0], meal_lunch=f['meal'][1], meal_dinner=f['meal'][2],
               meal_snacks=f['meal'][3], flags=f['flags'], cup_eq_g=f['cup_eq_g'], cap_group=f['cap_group'],
               dga_group=f['dga_group'], dga_serving_g=f['dga_serving_g'], refined_serving_g=f['refined_serving_g'],
               variety_key=f['variety_key'], satfat=f['satfat'], usda_ndb=f['ndb'], usda_desc=f['usda_desc'],
               **{k: p[k] for k in NUT})
    assert list(row) == fcols, set(row) ^ set(fcols)
    rows.append("  (" + ", ".join(v if isinstance(v, str) and v.endswith('::date') else q(v) for v in row.values()) + ")")
upd = ",\n  ".join(f"{c} = excluded.{c}" for c in fcols if c != 'id')
out += [f"insert into public.foods ({', '.join(fcols)}) values", ",\n".join(rows),
        f"on conflict (id) do update set\n  {upd},\n  updated_at = now();", ""]

drows = [f"  ({q(d['name'])}, {q(d['desc'])}, {i+1}, {d['protein'][0]}, {d['protein'][1]}, {d['carb'][0]}, {d['carb'][1]}, "
         f"{d['fat'][0]}, {d['fat'][1]}, {q(d['forbid'])}, {q(d.get('forbid_foods', []))})" for i, d in enumerate(D['diets'])]
out += ["insert into public.diets (name, description, sort_order, protein_min, protein_max, carb_min, carb_max, fat_min, fat_max, forbid, forbid_foods) values",
        ",\n".join(drows),
        "on conflict (name) do update set description = excluded.description, sort_order = excluded.sort_order,\n"
        "  protein_min = excluded.protein_min, protein_max = excluded.protein_max, carb_min = excluded.carb_min,\n"
        "  carb_max = excluded.carb_max, fat_min = excluded.fat_min, fat_max = excluded.fat_max, forbid = excluded.forbid,\n  forbid_foods = excluded.forbid_foods;", ""]

grows = [f"  ({q(g['key'])}, {q(g['label'])}, {q(g['unit'])}, {g['max']}, {q(g['note'] or None)})" for g in D['group_caps']]
out += ["insert into public.group_caps (key, label, unit, max_amount, note) values", ",\n".join(grows),
        "on conflict (key) do update set label = excluded.label, unit = excluded.unit, max_amount = excluded.max_amount, note = excluded.note;", ""]

S = {k: v for k, v in D['settings'].items() if k != 'group_caps'}
srows = [f"  ({q(k)}, {q(json.dumps(v))}::jsonb)" for k, v in S.items()]
out += ["insert into public.optimizer_settings (key, value) values", ",\n".join(srows),
        "on conflict (key) do update set value = excluded.value;", ""]

path = os.path.join(ROOT, 'supabase', 'migrations', '20261026193100_seed_diet_data.sql')
open(path, 'w').write("\n".join(out))
if '--release' in sys.argv:
    stamp = datetime.datetime.now(datetime.timezone.utc).strftime('%Y%m%d%H%M%S')
    rel = os.path.join(ROOT, 'supabase', 'migrations', f'{stamp}_update_diet_data.sql')
    open(rel, 'w').write("-- Data update: same upserts as 20261026193100_seed_diet_data.sql, regenerated from config/diets.json\n"
                         "-- and scripts/foods_v2.py. Diets or foods removed from those files are NOT deleted here.\n" + "\n".join(out))
    print('wrote release migration', rel)
print('wrote', path, f"({len(D['foods'])} foods, {len(D['diets'])} diets, {len(D['group_caps'])} group caps, {len(S)} settings)")
