"""Generate the Supabase data migration from data/foods.json (upserts, safe to re-run).
Output: supabase/migrations/20261026193100_seed_diet_data.sql
"""
import json, os
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
D = json.load(open(os.path.join(ROOT, 'data', 'foods.json')))

def q(v):
    if v is None: return 'null'
    if isinstance(v, bool): return 'true' if v else 'false'
    if isinstance(v, (int, float)): return repr(round(v, 6)) if isinstance(v, float) else str(v)
    if isinstance(v, (list, tuple)): return "array[" + ",".join(q(x) for x in v) + "]::text[]" if v else "'{}'::text[]"
    return "'" + str(v).replace("'", "''") + "'"

def observed(note):
    if 'Jun 2025' in note: return '2025-06-27'
    if 'Jul 2025' in note: return '2025-07-29'
    if 'BLS Sep 2026' in note: return '2026-09-30'
    if 'undated' in note: return None
    return '2026-10-26'

out = ["-- GENERATED by scripts/build_supabase.py from data/foods.json — edit scripts/foods_v2.py, not this file.",
       "-- Upserts: re-running updates prices/nutrients in place.", ""]
fcols = ['id', 'name', 'food_group', 'food_type', 'sort_order', 'store_product', 'price', 'package_g', 'edible_yield', 'price_note',
         'price_observed', 'bls_price', 'bls_unit_g', 'serving_g', 'serving_desc', 'max_servings', 'meal_breakfast', 'meal_lunch',
         'meal_dinner', 'meal_snacks', 'flags', 'cup_eq_g', 'cap_group', 'usda_ndb', 'usda_desc',
         'kcal', 'protein', 'carb', 'fat', 'fiber', 'sugar', 'calcium', 'iron', 'potassium', 'sodium', 'vitc']
rows = []
for i, f in enumerate(D['foods']):
    p = f['per100g']; bls = f['bls'] or [None, None]
    vals = [f['id'], f['name'], f['group'], f['type'], i + 1, f['product'], f['price'], f['package_g'], f['edible_yield'],
            f['price_note'] or None, observed(f['price_note']), bls[0], None if bls[1] is None else round(bls[1], 4), f['serving_g'],
            f['serving_desc'], f['max_servings'], *f['meal'], f['flags'], f['cup_eq_g'], f['cap_group'], f['ndb'], f['usda_desc'],
            *[p[k] for k in ['kcal', 'protein', 'carb', 'fat', 'fiber', 'sugar', 'calcium', 'iron', 'potassium', 'sodium', 'vitc']]]
    vals[10] = None if vals[10] is None else f"'{vals[10]}'::date"
    rows.append("  (" + ", ".join(v if isinstance(v, str) and v.endswith('::date') else q(v) for v in vals) + ")")
upd = ",\n  ".join(f"{c} = excluded.{c}" for c in fcols if c != 'id')
out += [f"insert into public.foods ({', '.join(fcols)}) values", ",\n".join(rows),
        f"on conflict (id) do update set\n  {upd},\n  updated_at = now();", ""]

drows = [f"  ({q(d['name'])}, {q(d['desc'])}, {i+1}, {d['protein'][0]}, {d['protein'][1]}, {d['carb'][0]}, {d['carb'][1]}, "
         f"{d['fat'][0]}, {d['fat'][1]}, {q(d['forbid'])})" for i, d in enumerate(D['diets'])]
out += ["insert into public.diets (name, description, sort_order, protein_min, protein_max, carb_min, carb_max, fat_min, fat_max, forbid) values",
        ",\n".join(drows),
        "on conflict (name) do update set description = excluded.description, sort_order = excluded.sort_order,\n"
        "  protein_min = excluded.protein_min, protein_max = excluded.protein_max, carb_min = excluded.carb_min,\n"
        "  carb_max = excluded.carb_max, fat_min = excluded.fat_min, fat_max = excluded.fat_max, forbid = excluded.forbid;", ""]

grows = [f"  ({q(g['key'])}, {q(g['label'])}, {q(g['unit'])}, {g['max']}, {q(g['note'] or None)})" for g in D['group_caps']]
out += ["insert into public.group_caps (key, label, unit, max_amount, note) values", ",\n".join(grows),
        "on conflict (key) do update set label = excluded.label, unit = excluded.unit, max_amount = excluded.max_amount, note = excluded.note;", ""]

S = {k: v for k, v in D['settings'].items() if k != 'group_caps'}
srows = [f"  ({q(k)}, {q(json.dumps(v))}::jsonb)" for k, v in S.items()]
out += ["insert into public.optimizer_settings (key, value) values", ",\n".join(srows),
        "on conflict (key) do update set value = excluded.value;", ""]

path = os.path.join(ROOT, 'supabase', 'migrations', '20261026193100_seed_diet_data.sql')
open(path, 'w').write("\n".join(out))
print('wrote', path, f"({len(D['foods'])} foods, {len(D['diets'])} diets, {len(D['group_caps'])} group caps, {len(S)} settings)")
